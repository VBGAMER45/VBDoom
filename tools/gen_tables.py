"""
gen_tables.py - converts the data tables of the GPL linuxdoom-1.10 source
into VB6 modules and a binary resource for DoomVB.

Generates:
  src/info_tables.bas    sprite/state/mobjtype/action enums + states, sprnames, mobjinfo
  src/sounds_tables.bas  sfx/music enums + S_sfx / S_music tables
  src/dstrings.bas       all strings from d_englsh.h
  src/d_items.bas        weaponinfo table
  res/tables.bin         finetangent, finesine, tantoangle, rndtable, gammatable
  res/doomvb.rc          resource script (compile with RC.EXE -> res/doomvb.res)

Usage: python tools/gen_tables.py  (run from the project root)
"""
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "ref", "linuxdoom-1.10")
OUT = os.path.join(ROOT, "src")
RES = os.path.join(ROOT, "res")

HEADER = (
    "' {name} - generated by tools/gen_tables.py from linuxdoom-1.10 ({src}).\n"
    "' DoomVB: a Visual Basic 6 port of the DOOM source release.\n"
    "' Copyright (C) 1993-1996 id Software, Inc.  Licensed under the GNU GPL v2.\n"
    "' DO NOT EDIT BY HAND - re-run the generator instead.\n"
    "Option Explicit\n\n"
)

STATE_CHUNK = 160      # states per init procedure (keeps procedures well under 64K)
MOBJ_CHUNK = 40


def read(name):
    with open(os.path.join(SRC, name), "r", encoding="latin-1") as f:
        return f.read()


def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    s = re.sub(r"//[^\n]*", "", s)
    return s


def write(path, text):
    with open(path, "w", encoding="latin-1", newline="\r\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, ROOT))


def enum_members(src, terminator):
    """Return the member list of the C enum ending with `terminator`."""
    end = re.search(r"\b" + terminator + r"\b", src)
    if not end:
        raise SystemExit("enum not found: " + terminator)
    start = src.rfind("enum", 0, end.start())
    brace = src.index("{", start)
    body = strip_comments(src[brace + 1:end.start()])
    names = []
    for part in body.split(","):
        part = part.strip()
        if not part:
            continue
        names.append(part.split("=")[0].strip())
    return names


def c_expr_to_vb(e):
    e = e.strip()
    e = re.sub(r"0x([0-9a-fA-F]+)", lambda m: "&H" + m.group(1).upper() + "&", e)
    e = e.replace("|", " Or ")
    e = re.sub(r"\s*\*\s*", " * ", e)
    if e == "NULL":
        e = "0"
    return e


def vb_string_literal(s):
    """Convert a C string body (without quotes, escapes intact) to a VB expression."""
    parts = []
    cur = ""
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            if n == "n":
                parts.append('"' + cur + '"')
                parts.append("vbLf")
                cur = ""
            elif n == "t":
                parts.append('"' + cur + '"')
                parts.append("vbTab")
                cur = ""
            elif n == "\\":
                cur += "\\"
            elif n == '"':
                cur += '""'
            elif n == "'":
                cur += "'"
            else:
                cur += n
            i += 2
            continue
        if c == '"':
            cur += '""'
        else:
            cur += c
        i += 1
    parts.append('"' + cur + '"')
    parts = [p for p in parts if p != '""'] or ['""']
    return " & ".join(parts)


# ---------------------------------------------------------------- info
def gen_info():
    h = read("info.h")
    c = strip_comments(read("info.c"))

    sprites = enum_members(h, "NUMSPRITES")
    states = enum_members(h, "NUMSTATES")
    mobjtypes = enum_members(h, "NUMMOBJTYPES")

    m = re.search(r"sprnames\s*\[[^\]]*\]\s*=\s*\{(.*?)\};", c, re.S)
    sprnames = re.findall(r'"([^"]*)"', m.group(1))
    assert len(sprnames) == len(sprites), (len(sprnames), len(sprites))

    m = re.search(r"state_t\s+states\s*\[[^\]]*\]\s*=\s*\{(.*)\};\s*mobjinfo_t", c, re.S)
    rows = re.findall(r"\{([^{}]*)\{([^{}]*)\}([^{}]*)\}", m.group(1))
    assert len(rows) == len(states), (len(rows), len(states))

    actions = []
    staterows = []
    for pre, act, post in rows:
        pre = [x.strip() for x in pre.split(",") if x.strip()]
        post = [x.strip() for x in post.split(",") if x.strip()]
        act = act.strip()
        if act in ("NULL", "0", ""):
            actname = "AF_NULL"
        else:
            if act not in actions:
                actions.append(act)
            actname = "AF_" + act[2:]
        staterows.append((pre[0], c_expr_to_vb(pre[1]), c_expr_to_vb(pre[2]), actname,
                          post[0], c_expr_to_vb(post[1]), c_expr_to_vb(post[2])))

    m = re.search(r"mobjinfo_t\s+mobjinfo\s*\[[^\]]*\]\s*=\s*\{(.*)\};", c, re.S)
    mrows = re.findall(r"\{([^{}]*)\}", m.group(1))
    assert len(mrows) == len(mobjtypes), (len(mrows), len(mobjtypes))

    o = [HEADER.format(name="info_tables.bas", src="info.h / info.c").replace(
        "Option Explicit", 'Attribute VB_Name = "info_tables"\nOption Explicit', 1)]
    # Attribute line must be first; rebuild properly
    o = ['Attribute VB_Name = "info_tables"\n' + HEADER.format(name="info_tables.bas", src="info.h / info.c")]

    o.append("Public Enum spritenum_t\n")
    for i, n in enumerate(sprites):
        o.append("    %s = %d\n" % (n, i))
    o.append("    NUMSPRITES = %d\nEnd Enum\n\n" % len(sprites))

    o.append("Public Enum statenum_t\n")
    for i, n in enumerate(states):
        o.append("    %s = %d\n" % (n, i))
    o.append("    NUMSTATES = %d\nEnd Enum\n\n" % len(states))

    o.append("Public Enum mobjtype_t\n")
    for i, n in enumerate(mobjtypes):
        o.append("    %s = %d\n" % (n, i))
    o.append("    NUMMOBJTYPES = %d\nEnd Enum\n\n" % len(mobjtypes))

    o.append("' Action function ids. state_t.action holds one of these; the dispatchers\n"
             "' P_CallMobjAction / P_CallPspAction (p_enemy / p_pspr) map them to the A_xxx routines.\n")
    o.append("Public Enum actionf_t\n    AF_NULL = 0\n")
    for i, a in enumerate(actions):
        o.append("    AF_%s = %d\n" % (a[2:], i + 1))
    o.append("    NUMACTIONS = %d\nEnd Enum\n\n" % (len(actions) + 1))

    o.append("Public states() As state_t\nPublic sprnames() As String\nPublic mobjinfo() As mobjinfo_t\n\n")

    o.append("Public Sub InitInfoTables()\n")
    o.append("    ReDim states(0 To NUMSTATES - 1)\n")
    o.append("    ReDim sprnames(0 To NUMSPRITES)\n")
    o.append("    ReDim mobjinfo(0 To NUMMOBJTYPES - 1)\n")
    for i, n in enumerate(sprnames):
        o.append('    sprnames(%d) = "%s"\n' % (i, n))
    o.append('    sprnames(NUMSPRITES) = ""\n')
    nchunks = (len(staterows) + STATE_CHUNK - 1) // STATE_CHUNK
    for k in range(nchunks):
        o.append("    InitStates%d\n" % k)
    mchunks = (len(mrows) + MOBJ_CHUNK - 1) // MOBJ_CHUNK
    for k in range(mchunks):
        o.append("    InitMobjInfo%d\n" % k)
    o.append("End Sub\n\n")

    o.append("Private Sub DS(ByVal i As Long, ByVal spr As Long, ByVal frm As Long, ByVal tics As Long, "
             "ByVal act As Long, ByVal nxt As Long, ByVal m1 As Long, ByVal m2 As Long)\n"
             "    states(i).sprite = spr\n    states(i).frame = frm\n    states(i).tics = tics\n"
             "    states(i).action = act\n    states(i).nextstate = nxt\n"
             "    states(i).misc1 = m1\n    states(i).misc2 = m2\nEnd Sub\n\n")

    for k in range(nchunks):
        o.append("Private Sub InitStates%d()\n" % k)
        for idx in range(k * STATE_CHUNK, min(len(staterows), (k + 1) * STATE_CHUNK)):
            r = staterows[idx]
            o.append("    DS %s, %s, %s, %s, %s, %s, %s, %s\n" % ((states[idx],) + r))
        o.append("End Sub\n\n")

    fields = ["doomednum", "spawnstate", "spawnhealth", "seestate", "seesound", "reactiontime",
              "attacksound", "painstate", "painchance", "painsound", "meleestate", "missilestate",
              "deathstate", "xdeathstate", "deathsound", "speed", "radius", "height", "mass",
              "damage", "activesound", "flags", "raisestate"]
    o.append("Private Sub DM(ByVal i As Long, " + ", ".join("ByVal %s As Long" % f for f in fields) + ")\n")
    for f in fields:
        o.append("    mobjinfo(i).%s = %s\n" % (f, f))
    o.append("End Sub\n\n")
    for k in range(mchunks):
        o.append("Private Sub InitMobjInfo%d()\n" % k)
        for idx in range(k * MOBJ_CHUNK, min(len(mrows), (k + 1) * MOBJ_CHUNK)):
            vals = [c_expr_to_vb(v) for v in mrows[idx].split(",") if v.strip()]
            assert len(vals) == len(fields), (mobjtypes[idx], vals)
            o.append("    DM %s, %s\n" % (mobjtypes[idx], ", ".join(vals)))
        o.append("End Sub\n\n")

    write(os.path.join(OUT, "info_tables.bas"), "".join(o))
    return actions


# ---------------------------------------------------------------- sounds
def gen_sounds():
    h = read("sounds.h")
    c = strip_comments(read("sounds.c"))
    sfx = enum_members(h, "NUMSFX")
    mus = enum_members(h, "NUMMUSIC")

    m = re.search(r"musicinfo_t\s+S_music\[\]\s*=\s*\{(.*?)\};", c, re.S)
    musrows = re.findall(r"\{([^{}]*)\}", m.group(1))
    m = re.search(r"sfxinfo_t\s+S_sfx\[\]\s*=\s*\{(.*?)\};", c, re.S)
    sfxrows = re.findall(r"\{([^{}]*)\}", m.group(1))
    assert len(sfxrows) == len(sfx), (len(sfxrows), len(sfx))

    o = ['Attribute VB_Name = "sounds_tables"\n' + HEADER.format(name="sounds_tables.bas", src="sounds.h / sounds.c")]
    o.append("Public Enum sfxenum_t\n")
    for i, n in enumerate(sfx):
        o.append("    %s = %d\n" % (n, i))
    o.append("    NUMSFX = %d\nEnd Enum\n\n" % len(sfx))
    o.append("Public Enum musicenum_t\n")
    for i, n in enumerate(mus):
        o.append("    %s = %d\n" % (n, i))
    o.append("    NUMMUSIC = %d\nEnd Enum\n\n" % len(mus))
    o.append("Public S_sfx() As sfxinfo_t\nPublic S_music() As musicinfo_t\n\n")
    o.append("Public Sub InitSoundTables()\n")
    o.append("    ReDim S_sfx(0 To NUMSFX - 1)\n    ReDim S_music(0 To NUMMUSIC - 1)\n")
    for i, r in enumerate(sfxrows):
        p = [x.strip() for x in r.split(",")]
        name = p[0].strip('"')
        sing = "True" if p[1] == "true" else "False"
        link = p[3]
        if link in ("0", "NULL"):
            linkv = "-1"
        else:
            mm = re.match(r"&S_sfx\[(\w+)\]", link)
            linkv = mm.group(1)
        o.append('    SetSfx %s, "%s", %s, %s, %s, %s, %s\n' % (sfx[i], name, sing, p[2], linkv, p[4], p[5]))
    for i, r in enumerate(musrows):
        names = re.findall(r'"([^"]*)"', r)
        o.append('    S_music(%d).name = "%s"\n' % (i, names[0] if names else ""))
    o.append("End Sub\n\n")
    o.append("Private Sub SetSfx(ByVal i As Long, ByVal nm As String, ByVal singularity As Boolean, "
             "ByVal priority As Long, ByVal lnk As Long, ByVal pitch As Long, ByVal volume As Long)\n"
             "    S_sfx(i).name = nm\n    S_sfx(i).singularity = singularity\n    S_sfx(i).priority = priority\n"
             "    S_sfx(i).link = lnk\n    S_sfx(i).pitch = pitch\n    S_sfx(i).volume = volume\n"
             "    S_sfx(i).lumpnum = -1\n    S_sfx(i).usefulness = 0\nEnd Sub\n")
    write(os.path.join(OUT, "sounds_tables.bas"), "".join(o))


# ---------------------------------------------------------------- strings
def gen_strings():
    src = read("d_englsh.h")
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    src = re.sub(r"\\\r?\n", " ", src)  # join continuation lines
    defs = {}
    order = []
    for line in src.splitlines():
        line = re.sub(r"//[^\n]*$", "", line) if '"' not in line else line
        m = re.match(r"\s*#define\s+(\w+)\s+(.*)$", line)
        if not m:
            continue
        name, val = m.group(1), m.group(2).strip()
        if name.startswith("__"):
            continue
        defs[name] = val
        order.append(name)

    out_vals = {}

    def expand(name, depth=0):
        val = defs[name]
        cm = re.fullmatch(r"'(\\?.)'", val)
        if cm:
            ch = cm.group(1)
            return ("char", ord(ch[-1]))
        toks = re.findall(r'"((?:[^"\\]|\\.)*)"|(\w+)', val)
        pieces = []
        for lit, ident in toks:
            if ident:
                if ident in defs:
                    kind, v = expand(ident, depth + 1)
                    pieces.append(v)
                else:
                    raise SystemExit("unknown macro in %s: %s" % (name, ident))
            else:
                pieces.append(lit)
        return ("str", "".join(pieces))

    o = ['Attribute VB_Name = "dstrings"\n' + HEADER.format(name="dstrings.bas", src="d_englsh.h")]
    consts = []
    strs = []
    for name in order:
        kind, v = expand(name)
        if kind == "char":
            consts.append("Public Const %s As Long = %d\n" % (name, v))
        else:
            strs.append((name, v))
    o.extend(consts)
    o.append("\n")
    for name, v in strs:
        o.append("Public %s As String\n" % name)
    o.append("\nPublic Sub InitStrings()\n")
    for name, v in strs:
        expr = vb_string_literal(v)
        # keep lines comfortably below VB6's 1023 character limit
        if len(expr) < 900:
            o.append("    %s = %s\n" % (name, expr))
        else:
            chunks = expr.split(" & ")
            o.append("    %s = \"\"\n" % name)
            cur = []
            for ch in chunks:
                cur.append(ch)
                if len(" & ".join(cur)) > 700:
                    o.append("    %s = %s & %s\n" % (name, name, " & ".join(cur)))
                    cur = []
            if cur:
                o.append("    %s = %s & %s\n" % (name, name, " & ".join(cur)))
    o.append("End Sub\n")
    write(os.path.join(OUT, "dstrings.bas"), "".join(o))


# ---------------------------------------------------------------- d_items
def gen_items():
    c = strip_comments(read("d_items.c"))
    m = re.search(r"weaponinfo\s*\[[^\]]*\]\s*=\s*\{(.*)\};", c, re.S)
    rows = re.findall(r"\{([^{}]*)\}", m.group(1))
    o = ['Attribute VB_Name = "d_items"\n' + HEADER.format(name="d_items.bas", src="d_items.c")]
    o.append("Public weaponinfo() As weaponinfo_t\n\n")
    o.append("Public Sub InitWeaponInfo()\n    ReDim weaponinfo(0 To NUMWEAPONS - 1)\n")
    for i, r in enumerate(rows):
        v = [x.strip() for x in r.split(",") if x.strip()]
        o.append("    SetWeapon %d, %s\n" % (i, ", ".join(v)))
    o.append("End Sub\n\n")
    o.append("Private Sub SetWeapon(ByVal i As Long, ByVal ammo As Long, ByVal upstate As Long, "
             "ByVal downstate As Long, ByVal readystate As Long, ByVal atkstate As Long, ByVal flashstate As Long)\n"
             "    weaponinfo(i).ammo = ammo\n    weaponinfo(i).upstate = upstate\n"
             "    weaponinfo(i).downstate = downstate\n    weaponinfo(i).readystate = readystate\n"
             "    weaponinfo(i).atkstate = atkstate\n    weaponinfo(i).flashstate = flashstate\nEnd Sub\n")
    write(os.path.join(OUT, "d_items.bas"), "".join(o))


# ---------------------------------------------------------------- binary tables
def c_array(src, name):
    m = re.search(name + r"\s*\[[^\]]*\](?:\s*\[[^\]]*\])?\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit("array not found: " + name)
    body = strip_comments(m.group(1))
    return [int(x, 0) for x in re.findall(r"-?(?:0x[0-9a-fA-F]+|\d+)", body)]


def gen_binary():
    t = read("tables.c")
    ft = c_array(t, "finetangent")
    fs = c_array(t, "finesine")
    ta = c_array(t, "tantoangle")
    rnd = c_array(read("m_random.c"), "rndtable")
    gam = c_array(read("v_video.c"), "gammatable")
    assert (len(ft), len(fs), len(ta), len(rnd), len(gam)) == (4096, 10240, 2049, 256, 1280)
    data = b""
    data += struct.pack("<4096i", *ft)
    data += struct.pack("<10240i", *fs)
    data += struct.pack("<2049I", *ta)
    data += bytes(rnd)
    data += bytes(gam)
    with open(os.path.join(RES, "tables.bin"), "wb") as f:
        f.write(data)
    with open(os.path.join(RES, "doomvb.rc"), "w", newline="\r\n") as f:
        f.write('101 CUSTOM "tables.bin"\n')
    print("wrote res/tables.bin (%d bytes)" % len(data))


def check_collisions():
    """VB is case-insensitive: make sure no generated identifiers collide."""
    names = {}
    for fn in ("info_tables.bas", "sounds_tables.bas", "dstrings.bas"):
        for line in open(os.path.join(OUT, fn), encoding="latin-1"):
            m = re.match(r"\s+(\w+) = -?\d+\s*$", line) or re.match(r"Public (?:Const )?(\w+) As", line)
            if m:
                k = m.group(1).lower()
                if k in names and names[k] != fn:
                    print("WARNING: case-insensitive collision:", m.group(1), fn, names[k])
                names[k] = fn


if __name__ == "__main__":
    gen_info()
    gen_sounds()
    gen_strings()
    gen_items()
    gen_binary()
    check_collisions()
